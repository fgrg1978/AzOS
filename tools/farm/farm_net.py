"""What the host serves the board: a DHCP lease and the kernel over TFTP.

The board's U-Boot runs boot/boot.scr.cmd (compiled to boot.scr on its SD
card): `dhcp ${kernel_addr_r} kernel.bin`. So the host needs a DHCP server
that hands the board its address with a boot file and a next server, and a
TFTP server with that file in its root. dnsmasq does both; `dnsmasq_conf`
writes its configuration for exactly one board, and `stage` puts the kernel in
the TFTP root. `tftp_get` is the check that the TFTP server in front of the
board really serves what was staged, so a dead server is reported as that and
not as a board that never booted.
"""

from __future__ import annotations

import os
import socket
import struct

from farm_config import Board, ConfigError

TFTP_RRQ, TFTP_DATA, TFTP_ACK, TFTP_ERROR = 1, 3, 4, 5
TFTP_BLOCK = 512
TFTP_TIMEOUT_S = 2.0
TFTP_TRIES = 3


def dnsmasq_conf(board: Board) -> str:
    """The dnsmasq configuration serving `board` and nobody else: DNS off, one
    interface, one static lease, `dhcp-ignore` for every other client."""
    if not board.interface:
        raise ConfigError(f"[{board.name}] needs interface: a DHCP server must not listen on every network")
    return "\n".join([
        f"# Generated by tools/farm/farm.py net-config for the board [{board.name}]. Do not edit.",
        f"# Run as root:  dnsmasq --keep-in-foreground --conf-file=<this file>",
        "port=0",
        f"interface={board.interface}",
        "bind-interfaces",
        f"dhcp-range={board.board_ip},static,{board.netmask}",
        f"dhcp-host={board.mac},{board.board_ip},{board.name}",
        "dhcp-ignore=tag:!known",
        f"dhcp-boot={board.kernel_name},{board.name},{board.server_ip}",
        "enable-tftp",
        f"tftp-root={board.tftp_root}",
        "log-dhcp",
        "",
    ])


def stage(board: Board, kernel: str) -> str:
    """Publish `kernel` as the board's boot file; the board never sees half of it."""
    if not os.path.isdir(board.tftp_root):
        raise ConfigError(f"tftp_root {board.tftp_root} is not a directory")
    dst = os.path.join(board.tftp_root, board.kernel_name)
    tmp = dst + ".tmp"
    with open(kernel, "rb") as src, open(tmp, "wb") as out:
        out.write(src.read())
    os.replace(tmp, dst)
    return dst


def tftp_get(host: str, port: int, name: str) -> bytes:
    """Read `name` from a TFTP server (RFC 1350, octet mode, 512-byte blocks).
    Raises OSError when the server does not answer or refuses."""
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.settimeout(TFTP_TIMEOUT_S)
    try:
        last = struct.pack("!H", TFTP_RRQ) + name.encode() + b"\0octet\0"
        peer = (host, port)
        data = b""
        block = 1
        tries = 0
        sock.sendto(last, peer)
        while True:
            try:
                pkt, addr = sock.recvfrom(TFTP_BLOCK + 4)
            except socket.timeout:
                tries += 1
                if tries >= TFTP_TRIES:
                    raise OSError(f"tftp {host}:{port}: no answer for {name}") from None
                sock.sendto(last, peer)
                continue
            if len(pkt) < 4:
                continue
            op, num = struct.unpack("!HH", pkt[:4])
            if op == TFTP_ERROR:
                raise OSError(f"tftp {host}:{port}: {name}: {pkt[4:-1].decode(errors='replace')}")
            if op != TFTP_DATA or num != block:
                continue
            peer = addr                       # the server answers from a port of its own
            tries = 0
            data += pkt[4:]
            last = struct.pack("!HH", TFTP_ACK, num)
            sock.sendto(last, peer)
            if len(pkt) - 4 < TFTP_BLOCK:
                return data
            block += 1
            if block > 0xFFFF:
                raise OSError(f"tftp {host}:{port}: {name} is larger than 65535 blocks")
    finally:
        sock.close()


def verify(board: Board) -> None:
    """The TFTP server answers and serves the staged kernel byte for byte."""
    with open(os.path.join(board.tftp_root, board.kernel_name), "rb") as f:
        want = f.read()
    got = tftp_get(board.server_ip, board.tftp_port, board.kernel_name)
    if got != want:
        raise OSError(f"tftp {board.server_ip}:{board.tftp_port} serves {len(got)} bytes of "
                      f"{board.kernel_name}, the staged file is {len(want)}: another TFTP root?")
