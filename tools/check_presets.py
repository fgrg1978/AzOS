"""check_presets.py — every preset expands on every ISA (`make check-presets`).

For each PRESET_* symbol of config/axes/Kconfig.preset and each ISA
(tools/kconfig_to_cargo.py ARCH_TO_TARGET), a two-line .config (the preset and
the ISA) is expanded with kconfiglib, as `olddefconfig` does, and handed to
tools/kconfig_to_cargo.py (the cargo arguments and the baseline rustflags).
A pair fails when:

  * the expansion warns (a value assigned and ignored: a `depends on` ate it);
  * the preset is not the one that came out, or an axis has no value;
  * kconfig_to_cargo.py fails, or names another target than the ISA's;
  * the QoS timer tolerance is not what the owner decided for the preset
    (QOS_TOLERANCE below);
  * the image is a small board (HWCLASS_EMBEDDED, as the preset sets it or
    forced on it) and a Linux adapter layer or a driver its config does not
    name is on (small_board_violations below).

Small boards run only the native drivers their board topology names; large
ones (sbc, desktop, server) may opt in to Linux drivers. The same rule is
asserted on every config/defconfigs/*.config of a small board, and a canary
(a server-class image with the Linux layers and a default-on driver) must
trip the same function, so a rule that went blind fails the check.

The kernels are not built; that is `make check` / the gate. Usage:

    python3 tools/check_presets.py [--list]
"""

import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
import azos_tools  # noqa: E402
ROOT = azos_tools.ROOT
import gen_userspace_kconfig as gus  # noqa: E402
import kconfig_to_cargo as k2c  # noqa: E402

# The axes (config/axes/Kconfig.preset; USE is the USE_* set, derived from the
# preset and never asked; BUILD_TYPE is the one of config/axes/Kconfig.build):
# each must come out with one member on, except USE for a preset that has no
# USE_* symbol (config/axes/Kconfig.use: one exists only where something reads it),
# which must come out with none.
AXIS_MEMBERS = {
    "HWCLASS": ["HWCLASS_EMBEDDED", "HWCLASS_SBC", "HWCLASS_DESKTOP", "HWCLASS_SERVER"],
    "USE": ["USE_GENERIC", "USE_ROBOT", "USE_IOT_HMI", "USE_GATEWAY", "USE_INDUSTRIAL",
            "USE_AUTOMOTIVE", "USE_DESKTOP", "USE_SERVER", "USE_WEARABLE"],
    "STRUCTURE": ["STRUCTURE_HYBRID", "STRUCTURE_RING3_DRIVERS"],
    "RT": ["RT_NONE", "RT_SOFT", "RT_HARD", "RT_MIXED"],
    "SECURITY": ["SECURITY_GENERAL", "SECURITY_HARDENED", "SECURITY_SEPARATION_STATIC",
                 "SECURITY_CONFIDENTIAL"],
    "BUILD_TYPE": ["BUILD_TYPE_DEV", "BUILD_TYPE_RELEASE", "BUILD_TYPE_CERTIFIABLE"],
    "VIRT": ["VIRT_NONE", "VIRT_HOSTED", "VIRT_SPLIT", "VIRT_STATIC"],
}


# Owner decision (QoS timer tolerance): on for every task of the desktop, IoT
# and wearable presets; opt-in per topology row on robot and industrial (and
# automotive, which is industrial); off elsewhere. (QOS_TIMER_TOLERANCE,
# QOS_TIMER_TOLERANCE_ROWS_ONLY) per preset.
_ALL, _ROWS, _OFF = ("y", "n"), ("y", "y"), ("n", "n")
QOS_TOLERANCE = {
    "PRESET_DESKTOP": _ALL, "PRESET_IOT_HMI": _ALL, "PRESET_WEARABLE": _ALL,
    "PRESET_ROBOT": _ROWS, "PRESET_INDUSTRIAL": _ROWS, "PRESET_AUTOMOTIVE": _ROWS,
    "PRESET_GENERIC": _OFF, "PRESET_GATEWAY": _OFF, "PRESET_SERVER": _OFF, "PRESET_FIRMWARE": _OFF,
}


# Hardware bus policy (HWBUS_AUTOBIND, config/subsys/Kconfig.drivers): the presets that
# are machines users plug things into bind what the driver tables match; the
# embedded-control presets (and the small-board firmware and wearable ones)
# detect everything and bind only what the signed topology admits.
HWBUS_POLICY = {
    "PRESET_GENERIC": "AUTO", "PRESET_DESKTOP": "AUTO", "PRESET_SERVER": "AUTO",
    "PRESET_IOT_HMI": "AUTO", "PRESET_GATEWAY": "AUTO",
    "PRESET_ROBOT": "TOPOLOGY", "PRESET_INDUSTRIAL": "TOPOLOGY", "PRESET_AUTOMOTIVE": "TOPOLOGY",
    "PRESET_FIRMWARE": "TOPOLOGY", "PRESET_WEARABLE": "TOPOLOGY",
}


# Owner rule: a small board (HWCLASS_EMBEDDED) uses only native drivers named by
# its board topology. LINUX_DRIVERS, LINUX_RUNTIME and every LX_* bool (the Linux
# adapter layers, the USB / audio / display / sensor / radio classes and the
# filesystem slice) are off whatever the config says (a `depends on`); a driver
# symbol is off unless the config names it (a preset or an `imply` is not the
# board naming it). A ring-3 image symbol (USERSPACE_<STEM>, generated by
# tools/gen_userspace_kconfig.py) is on only when the config names it or the
# image's `start` condition (its program metadata: the rows the topology
# starts) holds, and is on whenever that condition holds and the config does
# not say otherwise.
SMALL_BOARD_ALWAYS_OFF = ("LINUX_DRIVERS", "LINUX_RUNTIME")
SMALL_BOARD_ALWAYS_OFF_PREFIXES = ("LX_",)
SMALL_BOARD_NAMED_ONLY_PREFIXES = ("DRV_", "FB_", "USB_", "HID_", "SND_", "AUDIO_")
# Placement policy, not a driver.
SMALL_BOARD_NOT_DRIVERS = ("DRV_RING3_DEFAULT",)


_IMAGE_STARTS = None


def userspace_image_starts():
    """{USERSPACE_<STEM>: the Kconfig condition under which the topology starts
    the image, or None} for every image the program metadata under userspace/
    names (the symbols tools/gen_userspace_kconfig.py generates)."""
    global _IMAGE_STARTS
    if _IMAGE_STARTS is None:
        _IMAGE_STARTS = {"USERSPACE_" + gus.stem_of(img): meta.get("start")
                         for _, _, imgs, meta, _ in gus.scan(ROOT) for img in imgs}
    return _IMAGE_STARTS


def small_board_violations(kconf):
    """What is on in the loaded config that a small board must not have (or off
    that its topology starts), and how many symbols were examined per rule (so a
    rename cannot make the rule vacuous): (violations, {"always": n, "named": n,
    "images": n})."""
    from kconfiglib import BOOL

    bad, seen = [], {"always": 0, "named": 0, "images": 0}
    images = userspace_image_starts()
    for sym in kconf.unique_defined_syms:
        if sym.type != BOOL or sym.choice is not None:
            continue
        name = sym.name
        on = sym.str_value == "y"
        if name in images:
            seen["images"] += 1
            if sym.user_value is None:
                start = images[name]
                started = bool(start) and kconf.eval_string(start) == 2
                if on and not started:
                    bad.append(f"{name} is on, the config does not name it and the topology does not "
                               "start it: a small board builds only the images its topology starts")
                elif started and not on:
                    bad.append(f"{name} is off but the topology starts it ({start})")
        elif name in SMALL_BOARD_ALWAYS_OFF or name.startswith(SMALL_BOARD_ALWAYS_OFF_PREFIXES):
            seen["always"] += 1
            if on:
                bad.append(f"{name} is on: no Linux layer on a small board")
        elif name.startswith(SMALL_BOARD_NAMED_ONLY_PREFIXES) and name not in SMALL_BOARD_NOT_DRIVERS:
            seen["named"] += 1
            if on and sym.user_value is None:
                bad.append(f"{name} is on and the config does not name it: a small board "
                           "starts only the drivers its topology names")
    return bad, seen


def presets(kconf):
    """The members of the PRESET choice, in Kconfig order."""
    return [s.name for s in kconf.syms["PRESET_GENERIC"].nodes[0].parent.item.syms]


# What a config asks for to get the Linux layers; on a small board none of it may stick.
ASKED_LINUX = ["CONFIG_LINUX_ABI=y", "CONFIG_LINUX_RUNTIME=y", "CONFIG_LINUX_DRIVERS=y",
               "CONFIG_LX_SERVER_SKELETON=y", "CONFIG_LX_USB_XHCI=y", "CONFIG_LX_FS_EXT2=y"]


def _expand(kconf, path, lines):
    """Load a config made of `lines` (no warnings kept: the main sweep owns them)."""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("".join(f"{line}\n" for line in lines))
    kconf.load_config(path)


def _small_board_sweep(kconf, td, names, archs, failures):
    """The small-board rule beyond the presets' own HWCLASS: every preset on every
    ISA with HWCLASS_EMBEDDED forced and the Linux layers asked for, every defconfig that is a small board, and
    the canary. Failures are appended; returns the number of expansions."""
    cfg = os.path.join(td, "small.config")
    done = 0
    for preset in names:
        for arch in archs:
            _expand(kconf, cfg, [f"CONFIG_{preset}=y", f"{arch}=y", "CONFIG_HWCLASS_EMBEDDED=y", *ASKED_LINUX])
            done += 1
            bad = [] if kconf.syms["HWCLASS_EMBEDDED"].str_value == "y" else ["HWCLASS_EMBEDDED did not stay on"]
            bad += small_board_violations(kconf)[0]
            if bad:
                failures.append((f"{preset} on {arch.removeprefix('CONFIG_ARCH_').lower()} forced to HWCLASS_EMBEDDED", bad))
    defdir = os.path.join(ROOT, "config", "defconfigs")
    for fname in sorted(os.listdir(defdir)):
        path = os.path.join(defdir, fname)
        with open(path, encoding="utf-8") as fh:
            if "CONFIG_HWCLASS_EMBEDDED=y" not in fh.read().splitlines():
                continue
        kconf.load_config(path)
        done += 1
        bad = small_board_violations(kconf)[0]
        if bad:
            failures.append((f"defconfig {fname}", bad))
    # Canary: a server-class image that asks for the Linux layers must trip the
    # rule, on every ISA the Linux layers exist on, and the rule must have looked
    # at symbols of both kinds. If it does not, the rule is blind.
    for arch in archs:
        _expand(kconf, cfg, ["CONFIG_PRESET_GENERIC=y", f"{arch}=y", "CONFIG_HWCLASS_SERVER=y",
                             *ASKED_LINUX])
        bad, seen = small_board_violations(kconf)
        tag = f"canary on {arch.removeprefix('CONFIG_ARCH_').lower()}"
        wanted = {"LINUX_DRIVERS", "LINUX_RUNTIME", "LX_SERVER_SKELETON", "DRV_VIRTIO_INPUT", "USERSPACE_TOOLBOX"}
        missed = sorted(w for w in wanted if not any(b.startswith(w + " ") for b in bad))
        if missed:
            failures.append((tag, [f"the small-board rule did not flag {m} on a server-class image" for m in missed]))
        if not all(seen.values()):
            failures.append((tag, [f"the small-board rule examined {seen}: a prefix matches nothing"]))
        # The started-image exemption must discriminate. On a server-class image
        # DECISD.ELF is on by default; without the decision records its `start`
        # condition fails and the rule must flag it, with them it must not.
        no_records = ["# CONFIG_DECISION_REFUSALS_DURABLE is not set", "# CONFIG_DECISION_RECORDS_DEV is not set"]
        _expand(kconf, cfg, ["CONFIG_PRESET_GENERIC=y", f"{arch}=y", "CONFIG_HWCLASS_SERVER=y", *no_records])
        if not any(b.startswith("USERSPACE_DECISD ") for b in small_board_violations(kconf)[0]):
            failures.append((tag, ["the small-board rule did not flag USERSPACE_DECISD although "
                                   "the topology does not start it"]))
        _expand(kconf, cfg, ["CONFIG_PRESET_GENERIC=y", f"{arch}=y", "CONFIG_HWCLASS_SERVER=y",
                             "CONFIG_DECISION_REFUSALS_DURABLE=y"])
        if any(b.startswith("USERSPACE_DECISD ") for b in small_board_violations(kconf)[0]):
            failures.append((tag, ["the small-board rule flagged USERSPACE_DECISD although the "
                                   "topology starts it"]))
        # And on the small board itself: with the records the started image is
        # built, without them it is not, and neither is a violation.
        for records, built in (("CONFIG_DECISION_REFUSALS_DURABLE=y", "y"),
                               ("# CONFIG_DECISION_REFUSALS_DURABLE is not set", "n")):
            _expand(kconf, cfg, ["CONFIG_PRESET_GENERIC=y", f"{arch}=y", "CONFIG_HWCLASS_EMBEDDED=y",
                                 records, "# CONFIG_DECISION_RECORDS_DEV is not set"])
            got, bad = kconf.syms["USERSPACE_DECISD"].str_value, small_board_violations(kconf)[0]
            if got != built or bad:
                failures.append((tag, [f"small board with `{records}`: USERSPACE_DECISD is {got}, "
                                       f"wanted {built}; violations {bad}"]))
    return done


def main() -> int:
    from kconfiglib import Kconfig

    os.chdir(ROOT)
    kconf = Kconfig("Kconfig", warn_to_stderr=False)
    names = presets(kconf)
    if "--list" in sys.argv[1:]:
        print("\n".join(names))
        return 0
    archs = sorted(k2c.ARCH_TO_TARGET)
    failures = []
    with tempfile.TemporaryDirectory() as td:
        small_boards = _small_board_sweep(kconf, td, names, archs, failures)
        for preset in names:
            for arch in archs:
                tag = f"{preset} on {arch.removeprefix('CONFIG_ARCH_').lower()}"
                cfg = os.path.join(td, "x.config")
                with open(cfg, "w", encoding="utf-8") as fh:
                    fh.write(f"CONFIG_{preset}=y\n{arch}=y\n")
                before = len(kconf.warnings)
                kconf.load_config(cfg)
                bad = []
                if kconf.syms["HWCLASS_EMBEDDED"].str_value == "y":
                    small_boards += 1
                    bad += small_board_violations(kconf)[0]
                kconf.write_config(cfg)
                bad += list(kconf.warnings[before:])
                if kconf.syms[preset].str_value != "y":
                    bad.append(f"{preset} is not on after the expansion")
                want = QOS_TOLERANCE.get(preset)
                if want is None:
                    bad.append(f"{preset} has no QoS timer tolerance decision in QOS_TOLERANCE")
                else:
                    got = (kconf.syms["QOS_TIMER_TOLERANCE"].str_value,
                           kconf.syms["QOS_TIMER_TOLERANCE_ROWS_ONLY"].str_value)
                    if got != want:
                        bad.append(f"QOS_TIMER_TOLERANCE / _ROWS_ONLY are {got}, the decision is {want}")
                want_bus = HWBUS_POLICY.get(preset)
                if want_bus is None:
                    bad.append(f"{preset} has no hardware bus policy decision in HWBUS_POLICY")
                else:
                    on = [m for m in ("AUTO", "TOPOLOGY")
                          if kconf.syms["HWBUS_AUTOBIND_" + m].str_value == "y"]
                    if on != [want_bus]:
                        bad.append(f"HWBUS_AUTOBIND is {on}, the decision is {want_bus}")
                want_use = "USE_" + preset.removeprefix("PRESET_")
                has_use = want_use in kconf.syms and bool(kconf.syms[want_use].nodes)
                if has_use and kconf.syms[want_use].str_value != "y":
                    bad.append(f"{want_use} is not on: USE follows the preset 1:1")
                for axis, members in AXIS_MEMBERS.items():
                    on = [m for m in members if kconf.syms[m].str_value == "y"]
                    if len(on) != (0 if axis == "USE" and not has_use else 1):
                        bad.append(f"axis {axis} has {len(on)} members on: {on}")
                for extra in ([], ["--rustflags"]):
                    r = subprocess.run([sys.executable, os.path.join(ROOT, "tools/kconfig_to_cargo.py"), *extra, cfg],
                                       capture_output=True, text=True)
                    if r.returncode != 0:
                        bad.append(f"kconfig_to_cargo.py {' '.join(extra)}: {r.stderr.strip()[:200]}")
                    elif not extra and f"--target {k2c.ARCH_TO_TARGET[arch]}" not in r.stdout:
                        bad.append(f"kconfig_to_cargo.py names another target than {k2c.ARCH_TO_TARGET[arch]}")
                if bad:
                    failures.append((tag, bad))
    for tag, bad in failures:
        print(f"check-presets: FAIL {tag}")
        for b in bad:
            print(f"    {b}")
    if failures:
        return 1
    print(f"check-presets: ok ({len(names)} presets x {len(archs)} ISAs, "
          f"{small_boards} small-board expansions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
