//! Linker-script parameters for the translation granule.
//!
//! `arch/aarch64/boot/linker-aarch64.ld` aligns every output section to a page (W^X
//! remaps whole pages, so `.text` and `.rodata` must not share one) and
//! links the kernel `KERNEL_VA_OFFSET` above its load address. Both depend
//! on the granule the cargo features `page-16k` / `page-64k` select
//! (config/arch/Kconfig.isa `AARCH64_PAGE_*`; neither = 4 KiB). A linker script
//! cannot read a cargo feature, so this writes them into
//! `$OUT_DIR/azos_granule.ld`, which the script `INCLUDE`s through the
//! search path added below.
//!
//! The values are not trusted on their own: the script ASSERTs both against
//! absolute symbols `boot.S` emits from Rust's own constants
//! (`_azos_page_size_check`, `_kernel_va_offset_check`), so if this file
//! and `arch/aarch64/src/mmu.rs` ever disagree the kernel fails
//! to link. The riscv64 linker scripts do not include the file.
//!
//! It also owns the link half of virtual KASLR (config/kernel/Kconfig.hardening,
//! KASLR): any policy but `n`, where the choice exists, links the kernel as a
//! static position-independent executable, so the boot's relocation walk
//! (`*_early_kaslr`) has a table of `R_*_RELATIVE` entries to apply. The
//! decision is read from the same configuration `azos_limits` compiles the
//! policy from (`KCONFIG_CONFIG`, else the workspace `.config`), so the code
//! that slides the image and the link that makes sliding it sound can never
//! disagree, whichever command line built the kernel. They did once: every
//! gate and check-fast build passed only `kconfig_to_cargo.py --base`, the
//! link args lived in `--rustflags`, and a `probe` kernel with an empty table
//! slid its image anyway, its data still pointing at the link address (the
//! boot hung at the first indirect call after the NX sweep took X off that
//! address's alias).

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let f16 = env::var_os("CARGO_FEATURE_PAGE_16K").is_some();
    let f64 = env::var_os("CARGO_FEATURE_PAGE_64K").is_some();
    if f16 && f64 {
        panic!("kernel features `page-16k` and `page-64k` are exclusive (Kconfig AARCH64_PAGE_* is a choice)");
    }
    // Page size and input range, mirroring arch-aarch64's `Granule` table:
    // 4 KiB and 16 KiB walk three levels at 39 bits, 64 KiB needs 48.
    let (page, va_bits): (u64, u32) = if f64 {
        (65536, 48)
    } else if f16 {
        (16384, 39)
    } else {
        (4096, 39)
    };
    let offset: u64 = !((1u64 << va_bits) - 1);
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let text = format!(
        "/* Generated by kernel/build.rs from the cargo features page-16k/page-64k. */\n\
         AZOS_PAGE_SIZE = {page:#x};\n\
         KERNEL_VA_OFFSET_LITERAL = {offset:#x};\n"
    );
    let path = out.join("azos_granule.ld");
    // Rewrite only on change, so an unchanged granule does not relink.
    if fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        fs::write(&path, text).expect("write azos_granule.ld");
    }
    println!("cargo:rustc-link-search=native={}", out.display());
    println!("cargo:rerun-if-changed=build.rs");
    kaslr_link();
}

/// The `-pie` link of a kernel whose KASLR policy is not `n` (module doc).
/// `-pie` is explicit because the bare-metal targets do not ask for it,
/// `--no-dynamic-linker` keeps lld from wanting an interpreter, `-z notext`
/// lets read-only tables carry relocations (the boot applies them before the
/// pages are made read-only), `-z norelro` drops the RELRO segment nothing
/// would apply. The codegen half stays in tools/build/kconfig_to_cargo.py
/// (kaslr_rustflags): x86_64 needs `-C relocation-model=pie`, which only
/// RUSTFLAGS can set; a build without it fails to link here (`R_X86_64_32S`
/// in a `-pie` link) instead of producing an image the boot cannot slide.
fn kaslr_link() {
    // Bare-metal kernel builds only (a host `cargo test` of the crate links
    // nothing of this).
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("none") {
        return;
    }
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    if !matches!(arch.as_str(), "riscv64" | "aarch64" | "x86_64") {
        return;
    }
    // The same lookup as crates/core/limits/build.rs.
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("workspace root")
        .to_path_buf();
    let cfg = env::var("KCONFIG_CONFIG")
        .map(PathBuf::from)
        .unwrap_or_else(|_| root.join(".config"));
    println!("cargo:rerun-if-changed={}", cfg.display());
    println!("cargo:rerun-if-env-changed=KCONFIG_CONFIG");
    let text = fs::read_to_string(&cfg).unwrap_or_default();
    let on = |k: &str| text.lines().any(|l| l.trim() == format!("CONFIG_{k}=y"));
    // `azos_arch_api::kaslr::ENABLED`: available and not `n` (a choice with
    // no member set reads as `probe`, as ExtPolicy::from_kconfig does).
    if !on("KASLR_AVAILABLE") || on("KASLR_NEVER") {
        return;
    }
    for a in ["-pie", "--no-dynamic-linker", "-znotext", "-znorelro"] {
        println!("cargo:rustc-link-arg-bins={a}");
    }
}
