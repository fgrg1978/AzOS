//! Report descriptors the suites parse.
//!
//! **Provenance.** None of these was captured from a device in this
//! environment (there is no hardware here). The HID boot keyboard and mouse
//! are the examples of HID 1.11 appendix E (the driver carries the same
//! bytes); the QEMU tablet is the descriptor `hw/usb/dev-hid.c` gives
//! `usb-tablet`; the Logitech receiver mouse (report ID 2, 16 buttons, 12-bit
//! relative axes, wheel and AC Pan) and its HID++ vendor collections are
//! transcribed from the published structure of the Unifying receiver's
//! interfaces; the Apple-style keyboard (report IDs, a consumer collection, a
//! vendor feature collection) is reconstructed from the structure those
//! keyboards are known to use, not copied from one. Real captures belong here
//! when a board is on the desk (`usb/devN` names the device; a capture is one
//! `GET_DESCRIPTOR(Report)`).

