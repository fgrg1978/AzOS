pub fn hex(s: &str) -> Vec<u8> {
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()
}

/// Rewrite the checksum byte of the block at `block` (0 for the base block).
pub fn seal(b: &mut [u8], block: usize) {
    let blk = &mut b[block * BLOCK..(block + 1) * BLOCK];
    blk[127] = 0;
    blk[127] = 0u8.wrapping_sub(blk.iter().fold(0u8, |a, &x| a.wrapping_add(x)));
}

