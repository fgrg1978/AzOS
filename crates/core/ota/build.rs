//! OT05 — embed the production public key at compile time.
//!
//! Reads `tools/keys/prod_pub.bin` (the raw public key of the configured
//! signature algorithm, `azos_crypto::sig::SigAlg::CONFIGURED`) and emits its bytes as a
//! Rust slice to `$OUT_DIR/secure_boot_pubkey.rs`. The crate `include!()`s
//! that file from `secure_boot.rs`, which checks the length against the
//! algorithm's (`azos_crypto::sig::key_array`) and fails the build on a
//! mismatch. If the file is missing (typical for dev builds and CI), the slice
//! is empty and the key all zeros — the kernel treats that as "no trusted key"
//! → BootTrust::Unverified.
//!
//! Override path with PROD_PUBKEY_PATH env var if you need a different key
//! per build (e.g. staging vs production fleets).
//!
//! WHY this is here, not a feature flag:
//! - A feature flag would force every developer to pass `--features prod-key`,
//!   easy to forget. Reading a file is automatic and explicit.
//! - The build artifact captures which key is embedded — the kernel binary
//!   can be reproduced byte-for-byte from the same prod_pub.bin.

use std::env;
use std::fs;
use std::io::Write;
use std::path::PathBuf;

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR not set"));
    let dest = out_dir.join("secure_boot_pubkey.rs");

    // Default: tools/keys/prod_pub.bin relative to this crate.
    // ota crate is at crates/core/ota/, so up three levels = repo root.
    let manifest_dir = env::var("CARGO_MANIFEST_DIR")
        .expect("CARGO_MANIFEST_DIR not set");
    let default_path = PathBuf::from(&manifest_dir)
        .join("..").join("..").join("..")
        .join("tools").join("keys").join("prod_pub.bin");
    let key_path = env::var("PROD_PUBKEY_PATH")
        .map(PathBuf::from)
        .unwrap_or(default_path);

    println!("cargo:rerun-if-changed={}", key_path.display());
    println!("cargo:rerun-if-env-changed=PROD_PUBKEY_PATH");

    // Quiet fallback to no key — typical for dev builds. The kernel logs
    // "[SEC] WARNING: dev key embedded" at runtime.
    let bytes = fs::read(&key_path).unwrap_or_default();
    if !bytes.is_empty() {
        println!("cargo:warning=secure_boot: embedding prod pubkey from {}", key_path.display());
    }

    let mut out = fs::File::create(&dest).expect("write secure_boot_pubkey.rs");
    write!(out, "// Auto-generated by build.rs — do not edit.\n").unwrap();
    write!(out, "pub(crate) const SECURE_BOOT_PUBKEY_BYTES: &[u8] = &[").unwrap();
    for (i, b) in bytes.iter().enumerate() {
        if i > 0 { write!(out, ", ").unwrap(); }
        write!(out, "0x{:02x}", b).unwrap();
    }
    writeln!(out, "];").unwrap();
}
