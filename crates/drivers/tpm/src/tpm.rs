//! The commands AzOS sends a TPM 2.0.
//!
//! * `startup`: the first command after reset.
//! * `get_random`: the TPM's RNG, a hardware entropy source the kernel may
//!   credit to its pool (policy is the caller's: this returns bytes).
//! * `pcr_extend` / `pcr_read`: the measured-boot hook. One SHA-256 digest at
//!   a time into the SHA-256 bank; hashing is the caller's.
//! * `nv_define` / `nv_read_public` / `nv_read` / `nv_write` and `floor_*`:
//!   the anti-rollback floor in a 4-byte NV index. The floor only goes up:
//!   `floor_raise` reads first and never writes a value at or below the
//!   stored one. An index that already exists at provisioning is adopted only
//!   if `NV_ReadPublic` shows exactly the attributes, size, name algorithm
//!   and empty policy the driver defines; anything else fails closed. (What
//!   `NV_ReadPublic` cannot show is the index's auth value: the floor is as
//!   safe as that password is secret.)
//!
//! * `secret_*`: a 32-byte secret in an NV index of its own, for the
//!   keystore's TPM backend (`azos_crypto::keystore::Backend::TpmNv`). It is
//!   generated by the caller once and read at every boot; the index has the
//!   floor's shape (a password for both reads and writes, exempt from the
//!   dictionary-attack lockout) and is adopted under the same rule.
//!
//! Authorization is a password session only. Every parse goes through
//! [`wire::Reader`], so a size on the wire cannot read past the response.

use crate::tis::{Clock, DeviceInfo, Duration, Tis, TisRegs, RESP_MAX};
use crate::wire::{self, Cmd, Reader};
use crate::Error;

/// PCRs in the PC-client profile.
pub const PCR_COUNT: u8 = 24;
/// SHA-256 digest bytes.
pub const DIGEST_BYTES: usize = 32;
/// Longest auth value the driver passes (a `TPM2B_AUTH` holds at most a
/// digest; 32 covers the SHA-256 name algorithm of the floor index).
pub const AUTH_MAX: usize = 32;
/// Most NV bytes moved by one `nv_read` / `nv_write`.
pub const NV_MAX: usize = 128;
/// Size of the floor index: one big-endian `u32`.
pub const FLOOR_BYTES: u16 = 4;
/// Default NV index of the rollback floor: the owner range (`0x01000000`
/// to `0x01BFFFFF`), a number of our own.
pub const FLOOR_INDEX: u32 = 0x0150_0001;
/// `TPMA_NV` of the floor index: `AUTHWRITE` | `AUTHREAD` | `NO_DA` (the
/// dictionary-attack lockout must not be able to freeze the boot's floor
/// read). Type bits 7:4 are zero: an ordinary index.
pub const FLOOR_ATTRS: u32 = (1 << 2) | (1 << 18) | (1 << 25);
/// Size of the keystore secret's index: 32 bytes.
pub const SECRET_BYTES: u16 = 32;
/// Default NV index of the keystore secret: the owner range, next to the floor.
pub const SECRET_INDEX: u32 = 0x0150_0002;
/// `TPMA_NV` of the secret's index: the floor's (`AUTHWRITE` | `AUTHREAD` |
/// `NO_DA`).
pub const SECRET_ATTRS: u32 = FLOOR_ATTRS;
/// `TPMA_NV_WRITTEN`: set by the TPM after the first write. It is state, not
/// a property chosen at definition, so it is not compared.
const NV_WRITTEN: u32 = 1 << 29;

/// The public area of an NV index (`TPMS_NV_PUBLIC`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct NvPublic {
    pub index: u32,
    pub name_alg: u16,
    pub attrs: u32,
    /// Length of `authPolicy`; the digest itself is not kept.
    pub policy_len: u16,
    pub size: u16,
}

/// `TPM_SU` of `Startup`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StartupType {
    /// `TPM_SU_CLEAR`: a cold start.
    Clear = 0,
    /// `TPM_SU_STATE`: resume the state a `Shutdown(STATE)` saved.
    State = 1,
}

pub struct Tpm<R: TisRegs, C: Clock> {
    tis: Tis<R, C>,
}

fn pcr_mask(pcr: u8) -> [u8; 3] {
    let mut m = [0u8; 3];
    m[(pcr / 8) as usize] = 1 << (pcr % 8);
    m
}

impl<R: TisRegs, C: Clock> Tpm<R, C> {
    pub fn new(tis: Tis<R, C>) -> Self {
        Tpm { tis }
    }

    pub fn tis(&mut self) -> &mut Tis<R, C> {
        &mut self.tis
    }

    /// Identity registers, with a TPM 2.0 family check.
    pub fn probe(&mut self) -> Result<DeviceInfo, Error> {
        self.tis.probe()
    }

    /// Send `cmd`, check the response header, hand back the response in `out`.
    fn run<'a>(
        &mut self, cmd: Cmd, dur: Duration, tag: u16, out: &'a mut [u8; RESP_MAX],
    ) -> Result<&'a [u8], Error> {
        let n = self.tis.transmit(cmd.bytes_out(), &mut out[..], dur)?;
        wire::parse_response(&out[..n], tag)
    }

    /// `TPM2_Startup`. `TPM_RC_INITIALIZE` (already started) is success: the
    /// firmware ran Startup before us.
    pub fn startup(&mut self, kind: StartupType) -> Result<(), Error> {
        let mut c = Cmd::new(wire::ST_NO_SESSIONS, wire::CC_STARTUP);
        c.u16(kind as u16);
        let mut out = [0u8; RESP_MAX];
        match self.run(c.finish()?, Duration::Medium, wire::ST_NO_SESSIONS, &mut out) {
            Ok(_) | Err(Error::Tpm(wire::RC_INITIALIZE)) => Ok(()),
            Err(e) => Err(e),
        }
    }

    /// Fill `out` with TPM random bytes, 32 per command.
    pub fn get_random(&mut self, out: &mut [u8]) -> Result<(), Error> {
        let mut done = 0;
        while done < out.len() {
            let want = (out.len() - done).min(DIGEST_BYTES);
            let mut c = Cmd::new(wire::ST_NO_SESSIONS, wire::CC_GET_RANDOM);
            c.u16(want as u16);
            let mut buf = [0u8; RESP_MAX];
            let body = self.run(c.finish()?, Duration::Short, wire::ST_NO_SESSIONS, &mut buf)?;
            let mut r = Reader::new(body);
            let got = r.tpm2b()?;
            // An empty answer would loop forever; more than asked is a lie.
            if got.is_empty() || got.len() > want || r.remaining() != 0 {
                return Err(Error::Malformed);
            }
            out[done..done + got.len()].copy_from_slice(got);
            done += got.len();
        }
        Ok(())
    }

    /// `TPM2_PCR_Extend` of the SHA-256 bank.
    pub fn pcr_extend(&mut self, pcr: u8, digest: &[u8; DIGEST_BYTES]) -> Result<(), Error> {
        if pcr >= PCR_COUNT {
            return Err(Error::BadArgument);
        }
        let mut c = Cmd::new(wire::ST_SESSIONS, wire::CC_PCR_EXTEND);
        c.u32(pcr as u32);
        c.pw_auth(&[]);
        c.u32(1);
        c.u16(wire::ALG_SHA256);
        c.bytes(digest);
        let mut out = [0u8; RESP_MAX];
        let body = self.run(c.finish()?, Duration::Short, wire::ST_SESSIONS, &mut out)?;
        wire::session_params(body).map(|_| ())
    }

    /// `TPM2_PCR_Read` of one PCR in the SHA-256 bank.
    pub fn pcr_read(&mut self, pcr: u8) -> Result<[u8; DIGEST_BYTES], Error> {
        if pcr >= PCR_COUNT {
            return Err(Error::BadArgument);
        }
        let mask = pcr_mask(pcr);
        let mut c = Cmd::new(wire::ST_NO_SESSIONS, wire::CC_PCR_READ);
        c.u32(1);
        c.u16(wire::ALG_SHA256);
        c.u8(3);
        c.bytes(&mask);
        let mut out = [0u8; RESP_MAX];
        let body = self.run(c.finish()?, Duration::Short, wire::ST_NO_SESSIONS, &mut out)?;
        let mut r = Reader::new(body);
        let _update_counter = r.u32()?;
        // The selection actually read: it must be exactly the one asked for
        // (a PCR the bank does not have comes back unselected).
        if r.u32()? != 1 || r.u16()? != wire::ALG_SHA256 {
            return Err(Error::Malformed);
        }
        if r.u8()? != 3 || r.bytes(3)? != &mask[..] {
            return Err(Error::Malformed);
        }
        if r.u32()? != 1 {
            return Err(Error::Malformed);
        }
        let d = r.tpm2b()?;
        if d.len() != DIGEST_BYTES || r.remaining() != 0 {
            return Err(Error::Malformed);
        }
        let mut v = [0u8; DIGEST_BYTES];
        v.copy_from_slice(d);
        Ok(v)
    }

    /// `TPM2_NV_DefineSpace` (the slow class: it allocates NV flash) of an ordinary index of `size` bytes, owner
    /// hierarchy authorized by `owner_auth`, the index's own password
    /// `auth`. `TPM_RC_NV_DEFINED` comes back as `Err(Tpm(..))`.
    pub fn nv_define(
        &mut self, owner_auth: &[u8], index: u32, attrs: u32, size: u16, auth: &[u8],
    ) -> Result<(), Error> {
        if owner_auth.len() > AUTH_MAX || auth.len() > AUTH_MAX {
            return Err(Error::BadArgument);
        }
        let mut c = Cmd::new(wire::ST_SESSIONS, wire::CC_NV_DEFINE_SPACE);
        c.u32(wire::RH_OWNER);
        c.pw_auth(owner_auth);
        c.tpm2b(auth);
        // TPM2B_NV_PUBLIC: index, nameAlg, attributes, empty policy, size.
        c.u16(4 + 2 + 4 + 2 + 2);
        c.u32(index);
        c.u16(wire::ALG_SHA256);
        c.u32(attrs);
        c.u16(0);
        c.u16(size);
        let mut out = [0u8; RESP_MAX];
        let body = self.run(c.finish()?, Duration::Long, wire::ST_SESSIONS, &mut out)?;
        wire::session_params(body).map(|_| ())
    }

    /// `TPM2_NV_ReadPublic`: the public area of `index`. The reply must name
    /// the index asked for and carry nothing past the area and the name.
    pub fn nv_read_public(&mut self, index: u32) -> Result<NvPublic, Error> {
        let mut c = Cmd::new(wire::ST_NO_SESSIONS, wire::CC_NV_READ_PUBLIC);
        c.u32(index);
        let mut out = [0u8; RESP_MAX];
        let body = self.run(c.finish()?, Duration::Short, wire::ST_NO_SESSIONS, &mut out)?;
        let mut r = Reader::new(body);
        let area = r.tpm2b()?;
        let _name = r.tpm2b()?;
        if r.remaining() != 0 {
            return Err(Error::Malformed);
        }
        let mut a = Reader::new(area);
        let p = NvPublic {
            index: a.u32()?,
            name_alg: a.u16()?,
            attrs: a.u32()?,
            policy_len: a.tpm2b()?.len() as u16,
            size: a.u16()?,
        };
        if a.remaining() != 0 || p.index != index {
            return Err(Error::Malformed);
        }
        Ok(p)
    }

    /// `TPM2_NV_Write` of `data` at `offset`, authorized by the index's own
    /// password.
    pub fn nv_write(&mut self, index: u32, auth: &[u8], offset: u16, data: &[u8]) -> Result<(), Error> {
        if auth.len() > AUTH_MAX || data.is_empty() || data.len() > NV_MAX {
            return Err(Error::BadArgument);
        }
        let mut c = Cmd::new(wire::ST_SESSIONS, wire::CC_NV_WRITE);
        c.u32(index);
        c.u32(index);
        c.pw_auth(auth);
        c.tpm2b(data);
        c.u16(offset);
        let mut out = [0u8; RESP_MAX];
        let body = self.run(c.finish()?, Duration::Medium, wire::ST_SESSIONS, &mut out)?;
        wire::session_params(body).map(|_| ())
    }

    /// `TPM2_NV_Read` of `out.len()` bytes at `offset`.
    pub fn nv_read(&mut self, index: u32, auth: &[u8], offset: u16, out: &mut [u8]) -> Result<(), Error> {
        if auth.len() > AUTH_MAX || out.is_empty() || out.len() > NV_MAX {
            return Err(Error::BadArgument);
        }
        let mut c = Cmd::new(wire::ST_SESSIONS, wire::CC_NV_READ);
        c.u32(index);
        c.u32(index);
        c.pw_auth(auth);
        c.u16(out.len() as u16);
        c.u16(offset);
        let mut buf = [0u8; RESP_MAX];
        let body = self.run(c.finish()?, Duration::Medium, wire::ST_SESSIONS, &mut buf)?;
        let params = wire::session_params(body)?;
        let mut r = Reader::new(params);
        let data = r.tpm2b()?;
        if data.len() != out.len() || r.remaining() != 0 {
            return Err(Error::Malformed);
        }
        out.copy_from_slice(data);
        Ok(())
    }

    /// Define the NV index `index` once, at provisioning, with `attrs` and
    /// `size`. An index that already exists is success only if it is ours:
    /// `NV_ReadPublic` must show these attributes (the `WRITTEN` state bit
    /// aside), this size, the SHA-256 name algorithm and an empty policy.
    /// Anything else, for instance an index a previous owner defined with
    /// weaker rights, is `Err(NvMismatch)`: what the index holds would not
    /// hold.
    fn nv_adopt(
        &mut self, owner_auth: &[u8], index: u32, attrs: u32, size: u16, auth: &[u8],
    ) -> Result<(), Error> {
        match self.nv_define(owner_auth, index, attrs, size, auth) {
            Err(Error::Tpm(wire::RC_NV_DEFINED)) => {
                if cfg!(feature = "canary-nvsquat") {
                    return Ok(());
                }
                let p = self.nv_read_public(index)?;
                if p.attrs & !NV_WRITTEN == attrs
                    && p.size == size
                    && p.name_alg == wire::ALG_SHA256
                    && p.policy_len == 0
                {
                    Ok(())
                } else {
                    Err(Error::NvMismatch)
                }
            }
            r => r,
        }
    }

    /// Define the floor index ([`FLOOR_INDEX`] by default) once, at
    /// provisioning; an index that already exists is adopted only if it is the
    /// floor's (see `nv_adopt`).
    pub fn floor_provision(&mut self, owner_auth: &[u8], index: u32, auth: &[u8]) -> Result<(), Error> {
        self.nv_adopt(owner_auth, index, FLOOR_ATTRS, FLOOR_BYTES, auth)
    }

    /// The stored floor; 0 while the index is defined but never written.
    pub fn floor_read(&mut self, index: u32, auth: &[u8]) -> Result<u32, Error> {
        let mut b = [0u8; FLOOR_BYTES as usize];
        match self.nv_read(index, auth, 0, &mut b) {
            Ok(()) => Ok(u32::from_be_bytes(b)),
            Err(Error::Tpm(wire::RC_NV_UNINITIALIZED)) => Ok(0),
            Err(e) => Err(e),
        }
    }

    /// Raise the floor to `to` if that is higher than the stored value;
    /// returns the floor now in force. A value at or below the stored one is
    /// not written.
    pub fn floor_raise(&mut self, index: u32, auth: &[u8], to: u32) -> Result<u32, Error> {
        let cur = self.floor_read(index, auth)?;
        if to <= cur {
            return Ok(cur);
        }
        self.nv_write(index, auth, 0, &to.to_be_bytes())?;
        Ok(to)
    }

    /// Define the keystore secret's index ([`SECRET_INDEX`] by default) once,
    /// adopting an existing one only if it is ours (see `nv_adopt`).
    pub fn secret_provision(&mut self, owner_auth: &[u8], index: u32, auth: &[u8]) -> Result<(), Error> {
        self.nv_adopt(owner_auth, index, SECRET_ATTRS, SECRET_BYTES, auth)
    }

    /// The stored secret, or `None` while the index is defined but was never
    /// written.
    pub fn secret_read(&mut self, index: u32, auth: &[u8]) -> Result<Option<[u8; SECRET_BYTES as usize]>, Error> {
        let mut b = [0u8; SECRET_BYTES as usize];
        match self.nv_read(index, auth, 0, &mut b) {
            Ok(()) => Ok(Some(b)),
            Err(Error::Tpm(wire::RC_NV_UNINITIALIZED)) => Ok(None),
            Err(e) => Err(e),
        }
    }

    /// The secret of the index: the stored one if there is one, else `fresh`,
    /// which is written first and read back, so what is returned is what the
    /// TPM now holds and a second boot reads the same bytes. `fresh` is the
    /// caller's (random bytes it drew); it is never written over a stored
    /// secret.
    pub fn secret_load_or_create(
        &mut self, index: u32, auth: &[u8], fresh: &[u8; SECRET_BYTES as usize],
    ) -> Result<[u8; SECRET_BYTES as usize], Error> {
        if let Some(s) = self.secret_read(index, auth)? {
            return Ok(s);
        }
        self.nv_write(index, auth, 0, fresh)?;
        self.secret_read(index, auth)?.ok_or(Error::Malformed)
    }
}
