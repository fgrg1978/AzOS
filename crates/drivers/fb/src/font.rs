/// Expand the 5x7 columns into 8x16 cells: row `r` of the cell, bit 7 = the
/// leftmost pixel.
pub const fn expand(cols: &[[u8; 5]; COUNT]) -> [[u8; CELL_H]; COUNT] {
    let mut out = [[0u8; CELL_H]; COUNT];
    let mut g = 0;
    while g < COUNT {
        let mut gr = 0; // glyph row, 0..7
        while gr < 7 {
            let mut bits = 0u8;
            let mut x = 0;
            while x < 5 {
                if (cols[g][x] >> gr) & 1 != 0 {
                    bits |= 0x80 >> (x + 1);
                }
                x += 1;
            }
            out[g][1 + 2 * gr] = bits;
            out[g][2 + 2 * gr] = bits;
            gr += 1;
        }
        g += 1;
    }
    out
}

/// The 95 printable glyphs, 16 row bytes each.
pub static FONT: [[u8; CELL_H]; COUNT] = expand(&COLS);

/// The glyph for `c`; anything outside the printable ASCII range is `?`.
pub fn glyph(c: u8) -> &'static [u8; CELL_H] {
    let c = if (FIRST..=LAST).contains(&c) { c } else { b'?' };
    &FONT[(c - FIRST) as usize]
}
